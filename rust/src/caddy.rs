//! Caddy routing generation. Configuration is validated before rendering.
//! This module does not start Caddy or expose a network service.
use serde_json::Value;
use std::net::IpAddr;

fn text<'a>(root: &'a Value, key: &str, fallback: &'a str) -> Result<&'a str, &'static str> {
    match root.get(key) {
        None | Some(Value::Null) => Ok(fallback),
        Some(v) => v.as_str().ok_or("invalid string setting"),
    }
}
fn port(root: &Value, key: &str, fallback: u16) -> Result<u16, &'static str> {
    match root.get(key) {
        None | Some(Value::Null) => Ok(fallback),
        Some(v) => v
            .as_u64()
            .and_then(|n| u16::try_from(n).ok())
            .filter(|n| *n != 0)
            .ok_or("invalid port"),
    }
}
fn truth(root: &Value, key: &str) -> Result<bool, &'static str> {
    match root.get(key) {
        None | Some(Value::Null) => Ok(false),
        Some(v) => v.as_bool().ok_or("invalid boolean setting"),
    }
}
fn quote(input: &str) -> Result<String, &'static str> {
    if input.chars().any(|c| c.is_control()) {
        return Err("invalid control character");
    }
    Ok(format!(
        "\"{}\"",
        input.replace('\\', "\\\\").replace('"', "\\\"")
    ))
}
fn service_id(id: &str) -> bool {
    let b = id.as_bytes();
    !b.is_empty()
        && b.len() <= 24
        && b[0].is_ascii_lowercase()
        && b.iter()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || b"_-".contains(c))
}
fn route_valid(path: &str) -> bool {
    path.starts_with('/')
        && path.len() > 1
        && path.len() <= 49
        && path
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"/._~-".contains(&c))
        && !path.split('/').any(|part| part == "." || part == "..")
}
/// Render a configuration from explicit data. Never log or display the output:
/// token-protected routes necessarily embed the bearer token in the Caddyfile.
pub fn render(cfg: &Value, access_log: &str) -> Result<String, &'static str> {
    if !cfg.is_object() {
        return Err("invalid config");
    }
    let domain = text(cfg, "domain", "localhost")?.trim();
    let domain = if domain.is_empty() {
        "localhost"
    } else {
        domain
    };
    if domain.len() > 253
        || !domain
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b".-".contains(&c))
    {
        return Err("invalid domain");
    }
    let https = port(cfg, "httpsPort", 8443)?;
    let admin = port(cfg, "adminPort", 8765)?;
    let inspector = port(cfg, "inspectorPort", 8770)?;
    let caddy_admin = port(cfg, "caddyAdminPort", 2019)?;
    if https == admin
        || https == inspector
        || admin == inspector
        || [https, admin, inspector].contains(&caddy_admin)
    {
        return Err("conflicting ports");
    }
    let bind = text(cfg, "bind", "")?.trim();
    if !bind.is_empty()
        && bind
            .trim_start_matches('[')
            .trim_end_matches(']')
            .parse::<IpAddr>()
            .is_err()
    {
        return Err("invalid bind address");
    }
    let email = text(cfg, "email", "")?.trim();
    if !email.is_empty()
        && (email.len() > 254
            || !email.contains('@')
            || !email
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || b"@._+-".contains(&c)))
    {
        return Err("invalid email");
    }
    let token = text(cfg, "token", "")?;
    if token.len() > 4096 || token.chars().any(|c| c.is_control()) {
        return Err("invalid token");
    }
    let local = matches!(domain, "localhost" | "127.0.0.1");
    let plain = local || truth(cfg, "behindProxy")?;
    let mut lines = vec![
        "# Generated by MCP Hub - do not edit by hand.".to_string(),
        "{".into(),
    ];
    if plain {
        lines.push(format!("\thttp_port {https}"));
        lines.push("\tauto_https off".into());
    } else {
        lines.push(format!("\thttps_port {https}"));
        lines.push("\tauto_https disable_redirects".into());
    }
    lines.push(format!("\tadmin localhost:{caddy_admin}"));
    if !email.is_empty() {
        lines.push(format!("\temail {email}"));
    }
    lines.push("}".into());
    lines.push(String::new());
    let site = if plain && (!local || matches!(bind, "0.0.0.0" | "::" | "[::]")) {
        format!("http://:{https}")
    } else if local {
        format!("http://localhost:{https}")
    } else {
        domain.to_owned()
    };
    lines.push(format!("{site} {{"));
    if !bind.is_empty() {
        lines.push(format!("\tbind {bind}"));
    }
    if !plain && https != 443 {
        lines.push(format!("\t# Requires port forwarding 443 -> {https}."));
        lines.push("\ttls {".into());
        lines.push("\t\tissuer acme {".into());
        lines.push("\t\t\tdisable_http_challenge".into());
        lines.push(format!("\t\t\talt_tlsalpn_port {https}"));
        lines.push("\t\t}".into());
        lines.push("\t}".into());
    }
    let log = quote(&access_log.replace('\\', "/"))?;
    lines.extend([
        "\tlog {".into(),
        format!("\t\toutput file {log} {{"),
        "\t\t\troll_size 8mb".into(),
        "\t\t\troll_keep 3".into(),
        "\t\t}".into(),
        "\t}".into(),
    ]);
    lines.extend([
        "\thandle /healthz {".into(),
        "\t\trespond \"ok\" 200".into(),
        "\t}".into(),
    ]);
    for path in [
        "/.well-known/oauth-protected-resource*",
        "/.well-known/oauth-authorization-server*",
        "/.well-known/openid-configuration*",
        "/oauth/*",
        "/admin*",
    ] {
        lines.push(format!("\thandle {path} {{"));
        lines.push(format!("\t\treverse_proxy 127.0.0.1:{admin}"));
        lines.push("\t}".into());
    }
    let services = match cfg.get("services") {
        None => &[][..],
        Some(Value::Array(values)) => &values[..],
        _ => return Err("invalid services"),
    };
    let mut active: Vec<(String, String, String)> = Vec::new();
    for svc in services {
        if !svc.is_object() {
            return Err("invalid service");
        }
        if !truth(svc, "enabled")? {
            continue;
        }
        let id = text(svc, "id", "")?;
        if !service_id(id) {
            return Err("invalid service id");
        }
        if matches!(id, "windows" | "stabilitymatrix") {
            return Err("excluded built-in is enabled");
        }
        let path = text(svc, "path", "")?;
        if !route_valid(path)
            || ["/admin", "/healthz", "/oauth", "/.well-known"]
                .iter()
                .any(|reserved| path.starts_with(reserved) || reserved.starts_with(path))
        {
            return Err("invalid or reserved service path");
        }
        if active.iter().any(|(existing, prev, _)| {
            existing == id || prev.starts_with(path) || path.starts_with(prev)
        }) {
            return Err("overlapping service route");
        }
        let mode = text(svc, "authMode", "token")?;
        if !matches!(mode, "token" | "oauth" | "none") {
            return Err("invalid auth mode");
        }
        if mode == "token" && token.is_empty() {
            return Err("missing token for protected route");
        }
        active.push((id.to_owned(), path.to_owned(), mode.to_owned()));
    }
    if active.iter().any(|(_, _, mode)| mode == "token") {
        lines.push(format!(
            "\t@unauthorized not header Authorization {}",
            quote(&format!("Bearer {token}"))?
        ));
    }
    for (id, path, mode) in active {
        lines.push(format!("\thandle {path}* {{"));
        if mode == "token" {
            lines.push("\t\trespond @unauthorized \"unauthorized\" 401".into());
        }
        if mode == "oauth" {
            lines.push("\t\t# OAuth is validated by the inspector.".into());
        }
        lines.push(format!("\t\trewrite * /_inspect/{id}"));
        lines.push(format!("\t\treverse_proxy 127.0.0.1:{inspector} {{"));
        lines.push("\t\t\tflush_interval -1".into());
        lines.push("\t\t\tstream_close_delay 5m".into());
        lines.push("\t\t\ttransport http {".into());
        lines.push("\t\t\t\tversions 1.1".into());
        lines.push("\t\t\t}".into());
        lines.push("\t\t}".into());
        lines.push("\t}".into());
    }
    lines.extend([
        "\thandle {".into(),
        "\t\trespond \"not found\" 404".into(),
        "\t}".into(),
        "}".into(),
        String::new(),
    ]);
    Ok(lines.join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    #[test]
    fn exposes_only_enabled_routes_and_guards_tokens() {
        let cfg = json!({"domain":"localhost","token":"example-test-token","services":[
            {"id":"dc","path":"/mcp","enabled":true},
            {"id":"other","path":"/other","enabled":false}]});
        let out = render(&cfg, "access.log").unwrap();
        assert!(out.contains("handle /mcp*"));
        assert!(!out.contains("handle /other*"));
        assert!(out.contains("respond @unauthorized"));
        assert!(out.contains("flush_interval -1"));
        assert!(out.contains("handle /admin*"));
        assert!(out.contains("handle /healthz"));
    }
    #[test]
    fn tls_and_explicit_no_auth_match_expected_behavior() {
        let cfg = json!({"domain":"example.com","httpsPort":8443,"email":"admin@example.com","services":[{"id":"remote","path":"/remote","enabled":true,"authMode":"none"}]});
        let out = render(&cfg, "access.log").unwrap();
        assert!(out.contains("alt_tlsalpn_port 8443"));
        assert!(out.contains("email admin@example.com"));
        assert!(!out.contains("@unauthorized"));
    }
    #[test]
    fn fails_closed_on_missing_tokens_and_injection() {
        for cfg in [
            json!({"services":[{"id":"dc","path":"/mcp","enabled":true}]}),
            json!({"domain":"example.com\nrespond stolen"}),
            json!({"bind":"8443"}),
            json!({"token":"x","services":[{"id":"dc","path":"/adminx","enabled":true}]}),
            json!({"token":"x","services":[{"id":"dc","path":"/x","enabled":true},{"id":"xx","path":"/xyz","enabled":true}]}),
            json!({"token":"x","services":[{"id":"windows","path":"/windows","enabled":true}]}),
        ] {
            assert!(render(&cfg, "access.log").is_err());
        }
        assert!(render(&json!({}), "a\nlog").is_err());
    }
    #[test]
    fn caddyfile_adapts_if_caddy_is_available() {
        let Ok(bin) = std::env::var("CADDY_TEST_BIN") else {
            return;
        };
        let text = render(
            &json!({"token":"example","services":[{"id":"dc","path":"/mcp","enabled":true}]}),
            "access.log",
        )
        .unwrap();
        let path = std::env::temp_dir().join(format!("mcp-rs-caddy-test-{}", std::process::id()));
        std::fs::write(&path, text).unwrap();
        let result = std::process::Command::new(bin)
            .args(["adapt", "--adapter", "caddyfile", "--config"])
            .arg(&path)
            .output()
            .unwrap();
        let _ = std::fs::remove_file(path);
        assert!(
            result.status.success(),
            "caddy adapt failed: {}",
            String::from_utf8_lossy(&result.stderr)
        );
    }
}
